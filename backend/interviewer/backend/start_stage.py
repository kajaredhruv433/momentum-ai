"""
start_stage.py

Handles the opening stage of the interview:
1. Groq generates welcome greeting + first interview question (START_STAGE_PROMPT).
2. Groq decides which panel member asks it (START_PANEL_SELECTION_PROMPT).
3. Uses existing voice.py metadata for the selected panel member.
4. Sends the opening question to ElevenLabs adapter to speak via the panel member's voice.
5. TIMER DOES NOT START HERE (starts on ElevenLabs speech-start event).
"""
from __future__ import annotations

import logging
from typing import Any, Dict, List

try:
    from .otheragent import ask_groq
    from .prompts import START_PANEL_SELECTION_PROMPT, START_STAGE_PROMPT
    from .stage_utils import as_json, clean_text, validated_panel_member
except ImportError:
    from otheragent import ask_groq
    from prompts import START_PANEL_SELECTION_PROMPT, START_STAGE_PROMPT
    from stage_utils import as_json, clean_text, validated_panel_member

logger = logging.getLogger(__name__)


def create_start_action(
    company_details: Dict[str, Any],
    candidate_profile: Dict[str, Any],
    panel: Dict[str, Any],
    areas_to_cover: List[str],
) -> Dict[str, Any]:
    """
    Generate welcome greeting + first interview question and choose the first panel speaker.
    """
    # 1. Groq generates greeting + first question
    prompt = START_STAGE_PROMPT.format(
        company_details=as_json(company_details),
        candidate_resume=as_json(candidate_profile),
    )
    first_question = clean_text(ask_groq(prompt))

    # 2. Select initial evaluation area
    selected_area = areas_to_cover[0] if areas_to_cover else "Introduction"

    # 3. Groq selects which panel member asks the first question
    panel_prompt = START_PANEL_SELECTION_PROMPT.format(
        panels=as_json(panel),
        first_question=first_question,
    )
    selected_member = validated_panel_member(panel_prompt, panel)

    # 4. Extract panel member details from panel dict (which has voice.py metadata)
    member_details = None
    for _, member in panel.items():
        if isinstance(member, dict) and member.get("name") == selected_member:
            member_details = member
            break

    logger.info(
        "Start stage: first question generated by %s for area '%s': %s",
        selected_member, selected_area, first_question
    )

    return {
        "action": "ASK_QUESTION",
        "panel_member": selected_member,
        "panel_member_details": member_details,
        "question": first_question,
        "question_pattern": first_question,
        "selected_area": selected_area,
        "stage": "STARTING",
        "is_opening_question": True,
    }
